static void generate_literal_from_string(Environment *env, UDFContext *udfc, UDFValue *out){
	Literal* ret;
	CLIPSValue tmpcv;
	const char* datatype = (const char*) udfc->context;
	Literal* input = UDF_get_nth_as_literal(udfc, 1);
	const char* x = Literal_get_value(input);
	if(x == NULL){
		fprintf(stderr, "ERROR generate_literal_from_string\n");
		UDFThrowError(udfc);
		out->voidValue = VoidConstant(env);
		return;
	}
	ret = Literal_new(x, datatype);
	tmpcv = Literal_to_CLIPSValue(env, ret);
	out->value = tmpcv.value;
}
